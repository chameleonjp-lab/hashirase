import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { tokenizer, parse } from 'acorn';

const parts=['00-boot-audio','10-renderer-track','20-nyc-traffic','30-utility-poles','40-time-attack','50-police-scoring','60-collisions-damage','70-vehicle-model','80-interface-input','90-world-effects','99-physics-loop'];
/** One compatibility adapter, generated from the remaining authoritative fragments. */
export async function generateDrivingAdapter(rootDir,{check=false}={}) {
  const source=(await Promise.all(parts.map(name=>readFile(resolve(rootDir,`src/runtime/${name}.part.js`),'utf8')))).join('');
  const start=source.indexOf('__simStarted = true;')+'__simStarted = true;'.length;
  const end=source.indexOf('stepPhysics(0.016);\nupdateCamera(0.016);');
  if(start<20||end<start)throw Error('Legacy factory anchors changed; review the adapter extraction');
  let body=source.slice(start,end);
  body=body.replace('setTimeout(resolve, 140);',"if(context.abortSignal.aborted)throw context.abortSignal.reason;setTimeout(resolve,0);");
  body=body.replaceAll('random:Math.random','random:visualRandom.next');
  body=body.replaceAll('performance.now()','(simulationTime*1000)');
  const randomOwners={factory:'visual',createAsphaltTexture:'visual',createSkyscraperTexture:'visual',spawnCrashDebris:'visual',spawnSmokePuff:'visual',updateAll7RealismSystems:'visual',pickRandom38KmDestination:'physics',selectPoliceForwardOrSideSpawnPoint:'physics',updateNycTrafficAndCollisions:'physics',updateSubsystemDamageOnImpact:'physics',updateUrbanPropsAndPedestrians:'physics'};
  const prefix='async function factory(){';
  const edits=[];
  function randomReferences(node,scope='factory') {
    if(!node||typeof node!=='object')return;
    if(node.type==='FunctionDeclaration')scope=node.id.name;
    if(node.type==='MemberExpression'&&node.object?.name==='Math'&&node.property?.name==='random') {
      const stream=randomOwners[scope];if(!stream)throw Error(`Classify the new random owner: ${scope}`);
      edits.push({start:node.start-prefix.length,end:node.end-prefix.length,text:stream+'Random.next'});
    }
    for(const value of Object.values(node))if(Array.isArray(value))value.forEach(child=>randomReferences(child,scope));else if(value&&typeof value==='object')randomReferences(value,scope);
  }
  randomReferences(parse(prefix+body+'}',{ecmaVersion:'latest'}));
  for(const edit of edits.sort((a,b)=>b.start-a.start))body=body.slice(0,edit.start)+edit.text+body.slice(edit.end);
  // Rename identifiers, not strings/comments, to a private per-session facade.
  const tokens=[...tokenizer(body,{ecmaVersion:'latest',allowAwaitOutsideFunction:true})];
  for(const token of tokens.reverse())if(token.type.label==='name'&&['window','navigator'].includes(token.value)) {
    body=body.slice(0,token.start)+(token.value==='window'?'hostWindow':'hostNavigator')+body.slice(token.end);
  }
  const generated=`// Generated by scripts/build-driving-adapter.mjs. Edit src/runtime; do not hand-edit.\nimport {createCarState,createPursuitState,createTimeAttackState,DRIVING_TRIMS,drivingSnapshot} from './state.js';
import {stepVehicleState,createRampProfile,detachVehicle,beginKickflip,legacyInput} from './physics.js';
import {calculateCollisionDamage,scoreDrivingState,advanceDistance,createDrivingRules} from './rules.js';
import {createAudioService} from '../../platform/audio.js';
import {createRandom} from '../../platform/random.js';
export async function createLegacyEngine(surface,context,options={}) {
const {document,window:hostWindow,navigator:hostNavigator,THREE,setTimeout,clearTimeout}=surface;
const {applyDrivingVisuals,updateGameCamera}=surface.ports;
surface.setLegacyControls?.(options.legacyControls!==false);
const __drivingAudio=context.audio;
let __legacyBrakeReverse=options.legacyControls!==false;
let simulationTime=0;
const random=createRandom(options.seed??0x48415348),physicsRandom=random.fork('physics'),visualRandom=random.fork('visual');
${body}
if(options.trim)selectTrim(options.trim);
if(options.course==='NYC')changeCourse();
if(options.initial?.position){resetVehicle(options.initial.position.x,options.initial.position.z);carState.y=options.initial.position.y;}
hostWindow.__hideLoadingScreen();
const extractedRules=createDrivingRules(carState,policePursuitState,timeAttackState);
let pendingRenderTime=0,previousKick=false,disposed=false;
function clearInputs(){for(const key of Object.keys(inputs))inputs[key]=false;autoAccelLocked=false;activePointers.clear();updateAutoAccelUI();}
return Object.freeze({
step(dt,frame,environment={}){
  if(disposed)return;
  if(frame!==undefined){Object.assign(inputs,legacyInput(frame));__legacyBrakeReverse=false;if(frame.kickflip&&!previousKick)beginKickflip(carState,rampProfile.point);previousKick=frame.kickflip;}
  else if(options.legacyControls===false){clearInputs();__legacyBrakeReverse=false;}
  simulationTime+=dt;extractedRules.step(0,environment);stepPhysics(dt);pendingRenderTime+=dt;
},
snapshot(metadata){return drivingSnapshot(carState,policePursuitState,timeAttackState,{...metadata,course:currentCourse,trim:currentTrim.id,score:carState.score});},
reset(initial={}){clearInputs();stopAutoDemo();resetVehicle(initial.position?.x??0,initial.position?.z??(currentCourse==='NYC'?0:36));previousKick=false;pendingRenderTime=0;simulationTime=0;extractedRules.reset();},
pause(){clearInputs();},
render(){if(disposed)return;updateSmoke(pendingRenderTime);updateCamera(pendingRenderTime);renderer.render(scene,camera);pendingRenderTime=0;},
dispose(){if(disposed)return;disposed=true;clearInputs();surface.detach();}
});
}\n`;
  const output=resolve(rootDir,'src/modes/driving/legacy-adapter.js');
  if(check){if(await readFile(output,'utf8')!==generated)throw Error('Driving adapter is outdated. Run npm run build.');}
  else await writeFile(output,generated);
  return generated;
}
